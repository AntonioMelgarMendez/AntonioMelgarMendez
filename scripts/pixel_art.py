def pixel_width(value, scale=2):
    return max(0, (len(str(value)) * 6 - 1) * scale)


def pixel_text(x, y, value, scale=2, color="#f2d5a0"):
    value = str(value).upper()
    paths = []
    for index, char in enumerate(value):
        glyph = GLYPHS.get("E" if char == "É" else char)
        if glyph is None:
            raise ValueError(f"No pixel glyph for {char!r}")
        if char == "É":
            paths.append(f"M{index * 6 + 2} -2h1v1h-1zM{index * 6 + 3} -3h1v1h-1z")
        for row, line in enumerate(glyph.split("/")):
            for col, bit in enumerate(line):
                if bit == "1":
                    paths.append(f"M{index * 6 + col} {row}h1v1h-1z")
    return (f'<g transform="translate({x} {y}) scale({scale})" fill="{color}" '
            f'shape-rendering="crispEdges" aria-label="{escape(value)}">'
            f'<title>{escape(value)}</title><path d="{"".join(paths)}"/></g>')


def svg(width, height, title, body):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
            f'viewBox="0 0 {width} {height}" role="img" aria-label="{escape(title)}">'
            f'<title>{escape(title)}</title>{body}</svg>\n')
